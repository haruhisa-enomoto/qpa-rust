#!/usr/bin/env python3
"""Generate qpa-core's compact Conway table from the pinned GAP sources."""

from __future__ import annotations

import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
GAP = ROOT / "upstream" / "gap"
OUTPUT = ROOT / "crates" / "qpa-core" / "src" / "conway_table.tsv"


def top_level_entries(body: str) -> list[str]:
    entries: list[str] = []
    depth = 0
    start = 0
    for position, character in enumerate(body):
        if character == "[":
            depth += 1
        elif character == "]":
            depth -= 1
        elif character == "," and depth == 0:
            entries.append(body[start:position].strip())
            start = position + 1
    entries.append(body[start:].strip())
    return entries


def main() -> None:
    rows: list[tuple[int, int, str]] = []
    pattern = re.compile(r"SET_CONWAYPOLDATA\((\d+),\[(.*?)\]\);", re.DOTALL)
    entry_pattern = re.compile(r'^\[([0-9]+),"[^"]+"\]$')
    for source in sorted((GAP / "lib").glob("conwdat[123].g")):
        for table in pattern.finditer(source.read_text(encoding="utf-8")):
            characteristic = int(table.group(1))
            for degree, entry in enumerate(top_level_entries(table.group(2)), start=1):
                if degree == 1 or not entry:
                    continue
                matched = entry_pattern.fullmatch(entry)
                if matched is None:
                    raise ValueError(f"cannot parse {source}:{characteristic}^{degree}: {entry}")
                rows.append((characteristic, degree, matched.group(1)))

    rows.sort()
    if len(rows) != len({(p, n) for p, n, _ in rows}):
        raise ValueError("duplicate Conway table entry")
    revision = subprocess.run(
        ["git", "-C", str(GAP), "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    header = (
        "# Generated by scripts/generate-conway-table.py from pinned GAP "
        f"{revision}.\n"
        "# Format: characteristic<TAB>degree<TAB>base-p encoded coefficients.\n"
    )
    OUTPUT.write_text(
        header + "".join(f"{p}\t{n}\t{encoded}\n" for p, n, encoded in rows),
        encoding="ascii",
    )
    print(f"wrote {len(rows)} Conway polynomials to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
