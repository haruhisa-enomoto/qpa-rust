    fn check_dual_numbers<F: Field>(field: &F) {
        let quiver =
            Quiver::from_named(vec!["v".into()], vec![NamedArrowSpec::named("v", "v", "x")])
                .unwrap();
        let parent = PathAlgebra::new(field.clone(), quiver).unwrap();
        let x = parent.generators()[1].clone();
        let algebra = QuiverAlgebra::Quotient(
            quotient_by_relations(parent, &[x.multiply(&x).unwrap()]).unwrap(),
        );

        assert_eq!(loewy_length_of_algebra(&algebra).unwrap(), 2);
        let extension = trivial_extension_of_quiver_algebra(&algebra)
            .unwrap()
            .unwrap();
        assert_eq!(trivial_extension_level(&extension), 1);
        let quotient = extension.as_quotient().unwrap();
        assert_eq!(
            quotient.dimension().unwrap(),
            qpa_core::AlgebraDimension::Finite(4.into())
        );
        assert_eq!(
            extension
                .quiver()
                .arrows()
                .map(|arrow| arrow.name().to_owned())
                .collect::<Vec<_>>(),
            vec!["x".to_owned(), "te_a1_1_1".to_owned()]
        );
        let signatures = extension
            .relations()
            .iter()
            .map(|relation| {
                relation
                    .terms()
                    .iter()
                    .map(|term| {
                        (
                            term.path()
                                .walk()
                                .unwrap()
                                .iter()
                                .map(|index| {
                                    term.path()
                                        .quiver()
                                        .arrow(*index)
                                        .unwrap()
                                        .name()
                                        .to_owned()
                                })
                                .collect::<Vec<_>>(),
                            term.coefficient().clone(),
                        )
                    })
                    .collect::<Vec<_>>()
            })
            .collect::<Vec<_>>();
        let one = field.one();
        assert_eq!(
            signatures,
            vec![
                vec![(vec!["x".to_owned(), "x".to_owned()], one.clone())],
                vec![
                    (
                        vec!["x".to_owned(), "te_a1_1_1".to_owned()],
                        field.neg(&one),
                    ),
                    (vec!["te_a1_1_1".to_owned(), "x".to_owned()], one.clone(),),
                ],
                vec![(vec!["te_a1_1_1".to_owned(), "te_a1_1_1".to_owned()], one,)],
            ]
        );
    }

    #[test]
    fn rational_dual_numbers_match_pinned_qpa_trivial_extension() {
        check_dual_numbers(&Q);
    }

    #[test]
    fn binary_dual_numbers_match_pinned_qpa_trivial_extension() {
        check_dual_numbers(&Z2);
    }

    fn check_following_homomorphism_methods<F: Field>(field: F) {
        let algebra = a2(field);
        let projection = trivial_extension_of_quiver_algebra_projection(&algebra)
            .unwrap()
            .unwrap();
        assert!(projection.uses_generators_with_one());
        let source_generators = projection.source().generators_with_one().unwrap();
        let mut expected_images = algebra.generators_with_one().unwrap();
        expected_images.push(algebra.zero());
        assert_eq!(projection.generator_images(), expected_images);
        for (generator, expected) in source_generators.iter().zip(&expected_images) {
            assert_eq!(projection.image(generator).unwrap(), *expected);
        }

        let algebra_generators = algebra.generators_with_one().unwrap();
        let identity = QuiverAlgebraHomomorphism::by_generators_with_one_images(
            algebra.clone(),
            algebra.clone(),
            algebra_generators,
        )
        .unwrap();
        let opposite = opposite_algebra_homomorphism(&identity).unwrap();
        assert_eq!(opposite.generators(), opposite.generator_images());

        let enveloping = enveloping_algebra_homomorphism(&identity).unwrap();
        assert!(enveloping.uses_generators_with_one());
        assert_eq!(enveloping.generators(), enveloping.generator_images());
        for generator in enveloping.generators() {
            assert_eq!(enveloping.image(generator).unwrap(), *generator);
        }
    }

    #[test]
    fn rational_following_homomorphism_methods_match_qpa() {
        check_following_homomorphism_methods(Q);
    }

    #[test]
    fn binary_following_homomorphism_methods_match_qpa() {
        check_following_homomorphism_methods(Z2);
    }
