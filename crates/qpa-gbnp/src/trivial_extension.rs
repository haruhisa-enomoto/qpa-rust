//! QPA trivial extensions of finite quiver algebras.
//!
//! This is a direct translation of `TrivialExtensionOfQuiverAlgebra` in
//! `lib/pathalgtensor.gi`: it constructs the new arrows from the top of the
//! dual regular bimodule, transfers the old relations, forms the same
//! truncated temporary quotient, and obtains the remaining relations as the
//! left nullspace of the dual-bimodule action matrix.

use numerica::domains::Field;
use qpa_core::{
    DenseMatrix, MatrixError, NamedArrowSpec, Path, PathAlgebra, PathAlgebraElement,
    PathAlgebraError, PathAlgebraModuleError, PathAlgebraTensorError, PathError, Quiver,
    QuiverAlgebra, QuiverAlgebraElement, QuiverAlgebraElementError, QuiverAlgebraHomomorphism,
    QuiverAlgebraHomomorphismError, QuiverError, QuotientError, include_in_path_algebra,
    top_of_module_projection,
};
use thiserror::Error;

use crate::{
    EnvelopingModuleError, PathalgGbnpError, TensorProductError, enveloping_algebra,
    module::{dual_of_algebra_as_module_over_enveloping_algebra, finite_canonical_basis},
    opposite_quotient_element, quotient_by_relations,
};

/// Translate QPA's defaulting `TrivialExtensionOfQuiverAlgebraLevel` method.
#[must_use]
pub fn trivial_extension_level<F: Field>(algebra: &QuiverAlgebra<F>) -> usize {
    algebra.trivial_extension_level()
}

/// Translate QPA's `TrivialExtensionOfQuiverAlgebra(A)` method.
///
/// `Ok(None)` is the source method's `fail` result for infinite-dimensional
/// input.
///
/// # Errors
///
/// Propagates the source-translated enveloping-module, path-space, GBNP,
/// quotient, nullspace, and exact module-action computations. Internal errors
/// report violated invariants of objects generated by earlier QPA methods.
#[allow(clippy::too_many_lines)]
pub fn trivial_extension_of_quiver_algebra<F: Field>(
    algebra: &QuiverAlgebra<F>,
) -> Result<Option<QuiverAlgebra<F>>, TrivialExtensionError> {
    if let Some(cached) = algebra.cached_trivial_extension() {
        return Ok(Some(QuiverAlgebra::Quotient(cached)));
    }
    if algebra.trivial_extension_attribute_is_fail() {
        return Ok(None);
    }
    let Some(algebra_basis) = finite_canonical_basis(algebra)? else {
        algebra.mark_trivial_extension_attribute_fail();
        return Ok(None);
    };
    let next_level = algebra
        .trivial_extension_level()
        .checked_add(1)
        .ok_or(TrivialExtensionError::LevelOverflow)?;
    let original_quiver = algebra.quiver();

    let dual = dual_of_algebra_as_module_over_enveloping_algebra(algebra)?
        .ok_or(TrivialExtensionError::MissingFiniteDualBimodule)?;
    let top = top_of_module_projection(dual.clone())?;
    let top_basis = top.range().basis_elements();
    let enveloping = dual
        .retained_tensor_product()
        .ok_or(TrivialExtensionError::MissingRetainedEnvelopingAlgebra)?;
    let product = enveloping.product_quiver();

    let mut endpoint_pairs = Vec::with_capacity(top_basis.len());
    for basis_element in &top_basis {
        let support = basis_element.support_vertices();
        let [support] = support.as_slice() else {
            return Err(TrivialExtensionError::NonuniformTopBasisElement);
        };
        let product_vertex = enveloping
            .algebra()
            .quiver()
            .vertices()
            .nth(*support - 1)
            .ok_or(TrivialExtensionError::MissingTopSupportVertex)?;
        let first = qpa_core::project_from_product_quiver(1, &product_vertex.path(), product)?;
        let second = qpa_core::project_from_product_quiver(2, &product_vertex.path(), product)?;
        let source = first.quiver().opposite_quiver_name(&first.to_string())?;
        endpoint_pairs.push((source, second.to_string().into_boxed_str()));
    }

    let vertex_names = original_quiver
        .vertices()
        .map(|vertex| Box::<str>::from(vertex.name()))
        .collect::<Vec<_>>();
    let mut arrow_specs = original_quiver
        .arrows()
        .map(|arrow| {
            NamedArrowSpec::named(arrow.source().name(), arrow.target().name(), arrow.name())
        })
        .collect::<Vec<_>>();
    let mut additional_labels = Vec::with_capacity(endpoint_pairs.len());
    for (index, (source, target)) in endpoint_pairs.iter().enumerate() {
        let first_position = endpoint_pairs
            .iter()
            .position(|pair| pair == &(source.clone(), target.clone()))
            .ok_or(TrivialExtensionError::MissingEndpointPairPosition)?
            + 1;
        let label = format!("te_a{next_level}_{first_position}_{}", index + 1).into_boxed_str();
        arrow_specs.push(NamedArrowSpec::named(
            source.as_ref(),
            target.as_ref(),
            label.as_ref(),
        ));
        additional_labels.push(label);
    }

    let extension_quiver = Quiver::from_named(vertex_names, arrow_specs)?;
    let extension_parent = PathAlgebra::new(algebra.field().clone(), extension_quiver.clone())?;
    let old_arrow_count = original_quiver.number_of_arrows();
    let extension_arrows = extension_quiver.arrows().collect::<Vec<_>>();

    let mut new_relations = algebra
        .relations()
        .iter()
        .map(|relation| transfer_path_element(relation, &extension_parent))
        .collect::<Result<Vec<_>, _>>()?;

    let new_arrow_space = extension_arrows[old_arrow_count..]
        .iter()
        .map(|arrow| extension_parent.element(arrow.path()))
        .collect::<Result<Vec<_>, _>>()?;
    new_relations.extend(product_space_basis(&new_arrow_space, &new_arrow_space)?);

    let radical_basis = algebra_basis
        .iter()
        .skip(original_quiver.number_of_vertices())
        .map(representative_path_element)
        .map(|element| transfer_path_element(element, &extension_parent))
        .collect::<Result<Vec<_>, _>>()?;
    let radical_times_new = product_space_basis(&radical_basis, &new_arrow_space)?;
    new_relations.extend(product_space_basis(&new_arrow_space, &radical_times_new)?);

    let loewy_length = crate::loewy_length_of_algebra(algebra)?;
    let truncation_exponent = i64::try_from(
        loewy_length
            .checked_add(2)
            .ok_or(TrivialExtensionError::LoewyLengthOverflow)?,
    )
    .map_err(|_| TrivialExtensionError::LoewyLengthOverflow)?;
    let mut temporary_relations = new_relations.clone();
    temporary_relations.extend(extension_parent.nth_power_of_arrow_ideal(truncation_exponent)?);
    let temporary = quotient_by_relations(extension_parent.clone(), &temporary_relations)?;
    let temporary_basis = temporary
        .canonical_basis()?
        .ok_or(TrivialExtensionError::MissingTemporaryCanonicalBasis)?;

    let top_lifts = top_basis
        .iter()
        .map(|basis| {
            top.preimage_representative(basis)?
                .ok_or(TrivialExtensionError::MissingTopBasisPreimage)
        })
        .collect::<Result<Vec<_>, TrivialExtensionError>>()?;
    let original_parent = algebra.original_path_algebra();
    let mut selected_representatives = Vec::new();
    let mut action_rows = Vec::new();

    for basis_element in temporary_basis
        .iter()
        .skip(original_quiver.number_of_vertices())
    {
        let representative = basis_element.representative();
        let [term] = representative.terms() else {
            return Err(TrivialExtensionError::NonmonomialTemporaryBasis);
        };
        let walk = term
            .path()
            .walk()
            .ok_or(TrivialExtensionError::NonmonomialTemporaryBasis)?;
        let new_positions = walk
            .iter()
            .enumerate()
            .filter_map(|(position, arrow)| (arrow.get() > old_arrow_count).then_some(position))
            .collect::<Vec<_>>();
        let [new_position] = new_positions.as_slice() else {
            continue;
        };
        let new_arrow = extension_quiver
            .arrow(walk[*new_position])
            .ok_or(TrivialExtensionError::MissingTemporaryArrow)?;
        let lift_position = additional_labels
            .iter()
            .position(|label| label.as_ref() == new_arrow.name())
            .ok_or_else(|| TrivialExtensionError::MissingTopLiftForArrow {
                label: new_arrow.name().into(),
            })?;
        let initial = original_path_segment(
            original_parent,
            &extension_quiver,
            &walk[..*new_position],
            old_arrow_count,
        )?;
        let terminal = original_path_segment(
            original_parent,
            &extension_quiver,
            &walk[*new_position + 1..],
            old_arrow_count,
        )?;
        let (opposite_initial, terminal) = tensor_factors(algebra, &initial, &terminal)?;
        let tensor = enveloping.simple_tensor([&opposite_initial, &terminal])?;
        let image = top_lifts[lift_position].act(&tensor)?;
        action_rows.push(image.flat_external_representation());
        selected_representatives.push(representative.clone());
    }

    let action_width = dual
        .dimension_vector()
        .iter()
        .map(|dimension| dimension.max(&1))
        .sum::<usize>();
    let action_matrix = DenseMatrix::from_flat(
        action_rows.len(),
        action_width,
        action_rows.into_iter().flatten().collect(),
        algebra.field().clone(),
    )?;
    let solutions = action_matrix.nullspace_rows();
    for row in 0..solutions.nrows() {
        let mut relation = extension_parent.zero();
        for (coefficient, representative) in
            solutions.row(row).iter().zip(&selected_representatives)
        {
            relation = relation.add(&representative.scale_left(coefficient)?)?;
        }
        new_relations.push(relation);
    }

    let extension = quotient_by_relations(extension_parent, &new_relations)?;
    let extension = algebra.cache_trivial_extension(&extension);
    let result = QuiverAlgebra::Quotient(extension);
    result.set_trivial_extension_level(next_level);
    Ok(Some(result))
}

/// Translate QPA's cached `OppositeAlgebraHomomorphism(f)` construction.
///
/// Generator and image lists are taken from the mapping itself, mapped
/// termwise by `OppositePathAlgebraElement`, and installed on the
/// corresponding opposite algebras in the same list convention.
///
/// # Errors
///
/// Propagates opposite-algebra, opposite-element, and checked homomorphism
/// construction failures.
pub fn opposite_algebra_homomorphism<F: Field>(
    homomorphism: &QuiverAlgebraHomomorphism<F>,
) -> Result<QuiverAlgebraHomomorphism<F>, TrivialExtensionError> {
    let source = opposite_algebra(homomorphism.source())?;
    let range = opposite_algebra(homomorphism.range())?;
    let images = homomorphism
        .generator_images()
        .iter()
        .map(opposite_algebra_element)
        .collect::<Result<Vec<_>, _>>()?;
    if homomorphism.uses_generators_with_one() {
        Ok(QuiverAlgebraHomomorphism::by_generators_with_one_images(
            source, range, images,
        )?)
    } else {
        Ok(QuiverAlgebraHomomorphism::by_generator_images(
            source, range, images,
        )?)
    }
}

/// Translate QPA's `EnvelopingAlgebraHomomorphism(f)` method.
///
/// Every generator of `A^op tensor A` is projected to its two product-quiver
/// coordinates, mapped by `f^op` and `f`, and recombined by `SimpleTensor` in
/// `B^op tensor B`.
///
/// # Errors
///
/// Propagates opposite-map, enveloping-algebra, product projection, tensor,
/// and checked homomorphism failures.
pub fn enveloping_algebra_homomorphism<F: Field>(
    homomorphism: &QuiverAlgebraHomomorphism<F>,
) -> Result<QuiverAlgebraHomomorphism<F>, TrivialExtensionError> {
    let source_opposite = opposite_algebra(homomorphism.source())?;
    let source_enveloping = enveloping_algebra(homomorphism.source())?;
    let range_enveloping = enveloping_algebra(homomorphism.range())?;
    let opposite_homomorphism = opposite_algebra_homomorphism(homomorphism)?;
    let generators = source_enveloping.algebra().generators_with_one()?;
    let mut images = Vec::with_capacity(generators.len());

    for generator in &generators {
        let representative = match generator {
            QuiverAlgebraElement::Path(element) => element,
            QuiverAlgebraElement::Quotient(element) => element.representative(),
        };
        let [term] = representative.terms() else {
            return Err(TrivialExtensionError::NonmonomialEnvelopingGenerator);
        };
        let first_path = qpa_core::project_from_product_quiver(
            1,
            term.path(),
            source_enveloping.product_quiver(),
        )?;
        let second_path = qpa_core::project_from_product_quiver(
            2,
            term.path(),
            source_enveloping.product_quiver(),
        )?;
        let first = include_in_path_algebra(&first_path, &source_opposite)?;
        let second = include_in_path_algebra(&second_path, homomorphism.source())?;
        let first_image = opposite_homomorphism.image(&first)?;
        let second_image = homomorphism.image(&second)?;
        images.push(
            range_enveloping
                .simple_tensor([&first_image, &second_image])?
                .scale_left(term.coefficient())?,
        );
    }

    Ok(QuiverAlgebraHomomorphism::by_generators_with_one_images(
        source_enveloping.algebra().clone(),
        range_enveloping.algebra().clone(),
        images,
    )?)
}

/// Translate QPA's natural projection `TrivialExtensionOfQuiverAlgebraProjection(A)`.
///
/// `Ok(None)` is QPA's `fail` for infinite-dimensional input. Old vertices
/// and arrows map to the corresponding generators of `A`; every newly added
/// arrow maps to zero.
///
/// # Errors
///
/// Propagates trivial-extension and checked homomorphism construction
/// failures.
pub fn trivial_extension_of_quiver_algebra_projection<F: Field>(
    algebra: &QuiverAlgebra<F>,
) -> Result<Option<QuiverAlgebraHomomorphism<F>>, TrivialExtensionError> {
    if finite_canonical_basis(algebra)?.is_none() {
        return Ok(None);
    }
    let extension = trivial_extension_of_quiver_algebra(algebra)?
        .ok_or(TrivialExtensionError::MissingFiniteTrivialExtension)?;
    let extension_generators = extension.generators_with_one()?;
    let mut images = algebra.generators_with_one()?;
    let new_arrows = extension_generators
        .len()
        .checked_sub(images.len())
        .ok_or(TrivialExtensionError::ProjectionGeneratorCount)?;
    images.extend((0..new_arrows).map(|_| algebra.zero()));
    Ok(Some(
        QuiverAlgebraHomomorphism::by_generators_with_one_images(
            extension,
            algebra.clone(),
            images,
        )?,
    ))
}

fn opposite_algebra<F: Field>(
    algebra: &QuiverAlgebra<F>,
) -> Result<QuiverAlgebra<F>, TrivialExtensionError> {
    match algebra {
        QuiverAlgebra::Path(algebra) => Ok(QuiverAlgebra::Path(algebra.opposite()?)),
        QuiverAlgebra::Quotient(algebra) => Ok(QuiverAlgebra::Quotient(
            crate::opposite_path_algebra(algebra)?,
        )),
    }
}

fn opposite_algebra_element<F: Field>(
    element: &QuiverAlgebraElement<F>,
) -> Result<QuiverAlgebraElement<F>, TrivialExtensionError> {
    match element {
        QuiverAlgebraElement::Path(element) => Ok(QuiverAlgebraElement::Path(element.opposite()?)),
        QuiverAlgebraElement::Quotient(element) => Ok(QuiverAlgebraElement::Quotient(
            opposite_quotient_element(element)?,
        )),
    }
}

fn representative_path_element<F: Field>(
    element: &QuiverAlgebraElement<F>,
) -> &PathAlgebraElement<F> {
    match element {
        QuiverAlgebraElement::Path(element) => element,
        QuiverAlgebraElement::Quotient(element) => element.representative(),
    }
}

fn transfer_path_element<F: Field>(
    element: &PathAlgebraElement<F>,
    target: &PathAlgebra<F>,
) -> Result<PathAlgebraElement<F>, TrivialExtensionError> {
    target
        .from_terms(
            element
                .terms()
                .iter()
                .map(|term| {
                    Ok((
                        transfer_path(term.path(), target.quiver())?,
                        term.coefficient().clone(),
                    ))
                })
                .collect::<Result<Vec<_>, TrivialExtensionError>>()?,
        )
        .map_err(Into::into)
}

fn transfer_path(path: &Path, target: &Quiver) -> Result<Path, TrivialExtensionError> {
    let walk = path.walk().ok_or(TrivialExtensionError::ZeroPathTransfer)?;
    if walk.is_empty() {
        let qpa_core::PathEndpoint::Vertex(vertex) = path.source() else {
            return Err(TrivialExtensionError::ZeroPathTransfer);
        };
        return target
            .vertices()
            .find(|candidate| candidate.name() == vertex.name())
            .map(|vertex| vertex.path())
            .ok_or_else(|| TrivialExtensionError::MissingTransferredGenerator {
                name: vertex.name().into(),
            });
    }
    let mut transferred = Vec::with_capacity(walk.len());
    for arrow_index in walk {
        let source_arrow = path
            .quiver()
            .arrow(*arrow_index)
            .ok_or(TrivialExtensionError::MissingSourceArrow)?;
        let target_arrow = target
            .arrows()
            .find(|arrow| arrow.name() == source_arrow.name())
            .ok_or_else(|| TrivialExtensionError::MissingTransferredGenerator {
                name: source_arrow.name().into(),
            })?;
        transferred.push(target_arrow.path());
    }
    multiply_paths(&transferred)
}

fn multiply_paths(paths: &[Path]) -> Result<Path, TrivialExtensionError> {
    let (first, rest) = paths
        .split_first()
        .ok_or(TrivialExtensionError::EmptyPathProduct)?;
    let mut product = first.clone();
    for path in rest {
        product = product.multiply(path)?;
    }
    Ok(product)
}

fn product_space_basis<F: Field>(
    left: &[PathAlgebraElement<F>],
    right: &[PathAlgebraElement<F>],
) -> Result<Vec<PathAlgebraElement<F>>, PathAlgebraError> {
    let mut basis = Vec::new();
    for left in left {
        for right in right {
            let product = left.multiply(right)?;
            if !product.is_zero() && !basis.contains(&product) {
                basis.push(product);
            }
        }
    }
    Ok(basis)
}

fn original_path_segment<F: Field>(
    parent: &PathAlgebra<F>,
    extension_quiver: &Quiver,
    walk: &[qpa_core::ArrowIndex],
    old_arrow_count: usize,
) -> Result<PathAlgebraElement<F>, TrivialExtensionError> {
    let mut result = parent.one();
    for arrow_index in walk {
        if arrow_index.get() > old_arrow_count {
            return Err(TrivialExtensionError::NewArrowInsideOldSegment);
        }
        let extension_arrow = extension_quiver
            .arrow(*arrow_index)
            .ok_or(TrivialExtensionError::MissingTemporaryArrow)?;
        let original_arrow = parent
            .quiver()
            .arrows()
            .find(|arrow| arrow.name() == extension_arrow.name())
            .ok_or_else(|| TrivialExtensionError::MissingTransferredGenerator {
                name: extension_arrow.name().into(),
            })?;
        result = result.multiply(&parent.element(original_arrow.path())?)?;
    }
    Ok(result)
}

fn tensor_factors<F: Field>(
    algebra: &QuiverAlgebra<F>,
    initial: &PathAlgebraElement<F>,
    terminal: &PathAlgebraElement<F>,
) -> Result<(QuiverAlgebraElement<F>, QuiverAlgebraElement<F>), TrivialExtensionError> {
    match algebra {
        QuiverAlgebra::Path(_) => Ok((
            QuiverAlgebraElement::Path(initial.opposite()?),
            QuiverAlgebraElement::Path(terminal.clone()),
        )),
        QuiverAlgebra::Quotient(quotient) => {
            let initial = quotient.element(initial.clone())?;
            let terminal = quotient.element(terminal.clone())?;
            Ok((
                QuiverAlgebraElement::Quotient(opposite_quotient_element(&initial)?),
                QuiverAlgebraElement::Quotient(terminal),
            ))
        }
    }
}

/// Failure while translating QPA's trivial-extension construction.
#[derive(Clone, Debug, Eq, Error, PartialEq)]
pub enum TrivialExtensionError {
    /// Iterated trivial-extension naming exceeded addressable levels.
    #[error("the trivial-extension level overflows usize")]
    LevelOverflow,
    /// The `LoewyLength(A) + 2` truncation exponent overflowed.
    #[error("the trivial-extension truncation exponent overflows")]
    LoewyLengthOverflow,
    /// A finite algebra must produce its dual regular bimodule.
    #[error("a finite-dimensional algebra has no dual regular bimodule")]
    MissingFiniteDualBimodule,
    /// A finite algebra must produce its trivial extension.
    #[error("a finite-dimensional algebra did not produce its trivial extension")]
    MissingFiniteTrivialExtension,
    /// The dual bimodule created by QPA must retain its enveloping tensor.
    #[error("the dual regular bimodule lost its enveloping-algebra metadata")]
    MissingRetainedEnvelopingAlgebra,
    /// A canonical top basis element must be supported at exactly one vertex.
    #[error("a canonical top basis element is not supported at one product vertex")]
    NonuniformTopBasisElement,
    /// A recorded support position did not resolve in the enveloping quiver.
    #[error("cannot find the product vertex supporting a top basis element")]
    MissingTopSupportVertex,
    /// A currently iterated endpoint pair must occur in its containing list.
    #[error("cannot recover the first position of a new-arrow endpoint pair")]
    MissingEndpointPairPosition,
    /// The temporary finite quotient must expose its canonical basis.
    #[error("the temporary truncated quotient has no canonical basis")]
    MissingTemporaryCanonicalBasis,
    /// A top quotient basis vector must have a chosen QPA preimage.
    #[error("a top basis vector has no preimage in the dual bimodule")]
    MissingTopBasisPreimage,
    /// Canonical quotient basis vectors must be monomial representatives.
    #[error("the temporary quotient canonical basis contains a nonmonomial representative")]
    NonmonomialTemporaryBasis,
    /// Enveloping-algebra generators are product-quiver monomials.
    #[error("an enveloping-algebra generator has a nonmonomial representative")]
    NonmonomialEnvelopingGenerator,
    /// A temporary basis walk referred to an absent extension arrow.
    #[error("a temporary quotient basis walk contains an unknown arrow")]
    MissingTemporaryArrow,
    /// Every generated new-arrow label must index its corresponding top lift.
    #[error("new arrow {label:?} has no corresponding top-basis lift")]
    MissingTopLiftForArrow {
        /// Unresolved new-arrow label.
        label: Box<str>,
    },
    /// A source path walk referred to an absent arrow.
    #[error("a source path contains an unknown arrow")]
    MissingSourceArrow,
    /// A generator name from the old quiver was absent in the extension.
    #[error("cannot transfer old quiver generator {name:?}")]
    MissingTransferredGenerator {
        /// Missing generator name.
        name: Box<str>,
    },
    /// QPA's zero path is not a relation monomial.
    #[error("cannot transfer QPA's zero path")]
    ZeroPathTransfer,
    /// A path product helper received no paths where QPA supplies a unit.
    #[error("cannot form an empty path product")]
    EmptyPathProduct,
    /// The old-path portions around the unique new arrow cannot contain another new arrow.
    #[error("a new extension arrow occurred inside an old-path segment")]
    NewArrowInsideOldSegment,
    /// The extension generator list must contain the original list as a prefix.
    #[error("the trivial extension has fewer generators than its source algebra")]
    ProjectionGeneratorCount,
    /// Enveloping and dual-module construction failed.
    #[error(transparent)]
    Enveloping(#[from] EnvelopingModuleError),
    /// Tensor-product/enveloping-algebra construction failed.
    #[error(transparent)]
    TensorProduct(#[from] TensorProductError),
    /// Module top, preimage, or action construction failed.
    #[error(transparent)]
    Module(#[from] PathAlgebraModuleError),
    /// Configured QPA/GBNP quotient construction failed.
    #[error(transparent)]
    Backend(#[from] PathalgGbnpError),
    /// Parent path-algebra construction or arithmetic failed.
    #[error(transparent)]
    PathAlgebra(#[from] PathAlgebraError),
    /// Quiver path multiplication or opposite naming failed.
    #[error(transparent)]
    Path(#[from] PathError),
    /// Named extension-quiver construction failed.
    #[error(transparent)]
    Quiver(#[from] QuiverError),
    /// Product-quiver projection failed.
    #[error(transparent)]
    Product(#[from] qpa_core::QuiverProductError),
    /// Simple-tensor construction failed.
    #[error(transparent)]
    Tensor(#[from] PathAlgebraTensorError),
    /// Algebra-union arithmetic failed.
    #[error(transparent)]
    AlgebraElement(#[from] QuiverAlgebraElementError),
    /// Checked algebra-homomorphism construction failed.
    #[error(transparent)]
    Homomorphism(#[from] QuiverAlgebraHomomorphismError),
    /// Quotient element or canonical-basis construction failed.
    #[error(transparent)]
    Quotient(#[from] QuotientError),
    /// Exact matrix construction failed.
    #[error(transparent)]
    Matrix(#[from] MatrixError),
}

