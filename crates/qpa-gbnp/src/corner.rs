//! QPA's quiver presentation of an idempotent corner `eAe`.
//!
//! The implementation follows `QuiverAlgebraOfeAe` in `lib/pathalg.gi`:
//! construct the corner and its radical inside the entered admissible
//! quotient, lift semisimple idempotents, take arrow representatives from
//! `e_i rad(eAe)/rad(eAe)^2 e_j`, and recover a minimal relation space from
//! `ker(f)/(J ker(f) + ker(f) J)`.

use numerica::domains::Field;
use qpa_core::{
    DenseMatrix, PathAlgebra, PathAlgebraElement, PathEndpoint, QpaCoefficientField, Quiver,
    QuiverAlgebra, QuiverAlgebraElement, QuotientPathAlgebra, StructureConstantsAlgebra,
    StructureConstantsSubalgebra,
};

use crate::pathalg::{PathalgGbnpError, quotient_by_relations, quotient_is_admissible};

/// Translate QPA's `QuiverAlgebraOfeAe(A, e)` method.
///
/// QPA dispatches only for admissible quotients of path algebras. The corner
/// is represented temporarily by exact structure constants, but the returned
/// object is the same path-algebra or quotient presentation constructed by
/// the source method.
///
/// # Errors
///
/// Reproduces QPA's admissibility, membership, idempotence, and zero-corner
/// failures and propagates exact basis, structure-constant, quiver, path,
/// quotient, and GBNP failures.
#[allow(clippy::too_many_lines)]
pub fn quiver_algebra_of_eae<F: QpaCoefficientField>(
    algebra: &QuiverAlgebra<F>,
    idempotent: &QuiverAlgebraElement<F>,
) -> Result<QuiverAlgebra<F>, PathalgGbnpError> {
    let QuiverAlgebra::Quotient(quotient) = algebra else {
        return Err(PathalgGbnpError::NonAdmissibleCornerAlgebra);
    };
    if !quotient_is_admissible(quotient)? {
        return Err(PathalgGbnpError::NonAdmissibleCornerAlgebra);
    }
    let QuiverAlgebraElement::Quotient(idempotent) = idempotent else {
        return Err(PathalgGbnpError::CornerElementOutsideAlgebra);
    };
    if !quotient.is_identical(idempotent.algebra()) {
        return Err(PathalgGbnpError::CornerElementOutsideAlgebra);
    }
    let idempotent = idempotent.normalized()?;
    if idempotent.multiply(&idempotent)? != idempotent {
        return Err(PathalgGbnpError::CornerElementNotIdempotent);
    }

    let canonical_basis = quotient
        .canonical_basis()?
        .ok_or(PathalgGbnpError::MissingCornerCanonicalBasis)?;
    let ambient = quotient_structure_constants(quotient, &canonical_basis)?;
    let idempotent_coordinates = quotient.canonical_basis_coefficients(&idempotent)?;

    // eAe := FLMLORByGenerators(K, Filtered(e * Basis(A) * e, nonzero)).
    let mut corner_generators = Vec::new();
    for basis_index in 0..ambient.dimension() {
        let basis = standard_row(ambient.field(), ambient.dimension(), basis_index);
        let left = ambient.multiply_coordinates(&idempotent_coordinates, &basis)?;
        let sandwich = ambient.multiply_coordinates(&left, &idempotent_coordinates)?;
        if !is_zero_row(ambient.field(), &sandwich) {
            corner_generators.push(sandwich);
        }
    }
    if corner_generators.is_empty() {
        // GAP reaches `FLMLORByGenerators(K, [])` for the zero idempotent.
        return Err(PathalgGbnpError::ZeroCornerHasNoGenerators);
    }
    let corner_basis = span_basis(ambient.field(), ambient.dimension(), corner_generators)?;
    let corner = StructureConstantsSubalgebra::from_basis(ambient.clone(), corner_basis)?;
    let corner_algebra = corner.algebra();
    let corner_identity = corner
        .basis()
        .solution_row(&idempotent_coordinates)?
        .ok_or(PathalgGbnpError::CornerIdentityOutsideBasis)?;

    // rad(A) is the ideal generated by the original quiver arrows.
    let vertex_count = quotient
        .original_path_algebra()
        .quiver()
        .number_of_vertices();
    let quotient_generators = quotient.generators()?;
    let arrow_coordinates = quotient_generators[vertex_count..]
        .iter()
        .map(|arrow| quotient.canonical_basis_coefficients(arrow))
        .collect::<Result<Vec<_>, _>>()?;
    let radical_a = ideal_basis(&ambient, &arrow_coordinates)?;

    // erade := Ideal(eAe, Filtered(e * Basis(radA) * e, nonzero)).
    let mut corner_radical_generators = Vec::new();
    for row in 0..radical_a.nrows() {
        let left = ambient.multiply_coordinates(&idempotent_coordinates, radical_a.row(row))?;
        let sandwich = ambient.multiply_coordinates(&left, &idempotent_coordinates)?;
        if !is_zero_row(ambient.field(), &sandwich) {
            corner_radical_generators.push(
                corner
                    .basis()
                    .solution_row(&sandwich)?
                    .ok_or(PathalgGbnpError::CornerRadicalOutsideBasis)?,
            );
        }
    }
    let corner_radical = ideal_basis(corner_algebra, &corner_radical_generators)?;

    // QPA obtains central primitive idempotents in eAe/rad(eAe). Because the
    // entered algebra is an admissible (hence basic split) quiver quotient,
    // the nonzero distinct images of e v_i e are exactly those idempotents.
    // This source-specialized route also retains QPA's rational-field branch.
    let semisimple = corner_algebra.quotient_by_ideal_basis(corner_radical.clone())?;
    let mut central_idempotents = Vec::new();
    // `CentralIdempotentsOfAlgebra` returns a GAP `Set`; in QPA's path-ring
    // element ordering the vertex idempotents occur in reverse generator
    // order. Preserve that observable order before lifting.
    for vertex in quotient_generators[..vertex_count].iter().rev() {
        let vertex = quotient.canonical_basis_coefficients(vertex)?;
        let left = ambient.multiply_coordinates(&idempotent_coordinates, &vertex)?;
        let sandwich = ambient.multiply_coordinates(&left, &idempotent_coordinates)?;
        let Some(corner_coordinates) = corner.basis().solution_row(&sandwich)? else {
            return Err(PathalgGbnpError::CornerVertexOutsideBasis);
        };
        let projected = semisimple.project_coordinates(&corner_coordinates)?;
        if !is_zero_row(ambient.field(), &projected) && !central_idempotents.contains(&projected) {
            central_idempotents.push(projected);
        }
    }
    let corner_vertices =
        semisimple.lift_complete_set_of_orthogonal_idempotents(&central_idempotents)?;

    // ProductSpace(erade, erade), then eAe/rad(eAe)^2.
    let radical_square = product_space_basis(corner_algebra, &corner_radical, &corner_radical)?;
    let modulo_square = corner_algebra.quotient_by_ideal_basis(radical_square)?;
    let projected_radical = (0..corner_radical.nrows())
        .map(|row| modulo_square.project_coordinates(corner_radical.row(row)))
        .collect::<Result<Vec<_>, _>>()?;
    let radical_modulo_square = span_basis(
        ambient.field(),
        modulo_square.algebra().dimension(),
        projected_radical,
    )?;
    let projected_vertices = corner_vertices
        .iter()
        .map(|vertex| modulo_square.project_coordinates(vertex))
        .collect::<Result<Vec<_>, _>>()?;

    // QPA's row-major e_i rad/rad^2 e_j arrow spaces.
    let number_of_vertices = corner_vertices.len();
    let mut adjacency = vec![vec![0usize; number_of_vertices]; number_of_vertices];
    let mut corner_arrows = Vec::new();
    for left_vertex in 0..number_of_vertices {
        for right_vertex in 0..number_of_vertices {
            let mut candidates = Vec::new();
            for row in 0..radical_modulo_square.nrows() {
                let left = modulo_square.algebra().multiply_coordinates(
                    &projected_vertices[left_vertex],
                    radical_modulo_square.row(row),
                )?;
                let component = modulo_square
                    .algebra()
                    .multiply_coordinates(&left, &projected_vertices[right_vertex])?;
                if !is_zero_row(ambient.field(), &component) {
                    candidates.push(component);
                }
            }
            let arrow_space = span_basis(
                ambient.field(),
                modulo_square.algebra().dimension(),
                candidates,
            )?;
            adjacency[left_vertex][right_vertex] = arrow_space.nrows();
            for row in 0..arrow_space.nrows() {
                let representative = modulo_square.lift_coordinates(arrow_space.row(row))?;
                let left = corner_algebra
                    .multiply_coordinates(&corner_vertices[left_vertex], &representative)?;
                corner_arrows.push(
                    corner_algebra.multiply_coordinates(&left, &corner_vertices[right_vertex])?,
                );
            }
        }
    }

    // t = Length(RadicalSeriesOfAlgebra(eAe)) - 1 includes the terminal
    // zero radical power; QPA then truncates at J^(t+1).
    let radical_series_length_minus_one =
        radical_nilpotency_index(corner_algebra, &corner_radical)?;
    let truncation_power = radical_series_length_minus_one
        .checked_add(1)
        .ok_or(PathalgGbnpError::CornerLoewyLengthOverflow)?;
    let truncation_power =
        i64::try_from(truncation_power).map_err(|_| PathalgGbnpError::CornerLoewyLengthOverflow)?;
    let quiver = Quiver::from_adjacency(adjacency)?;
    let path_algebra = PathAlgebra::new(ambient.field().clone(), quiver)?;
    let arrow_power = path_algebra.nth_power_of_arrow_ideal(truncation_power)?;

    let mut generator_images = corner_vertices;
    generator_images.extend(corner_arrows);
    let (basis_representatives, truncated_algebra) = if arrow_power.is_empty() {
        let basis = path_algebra
            .canonical_basis()
            .ok_or(PathalgGbnpError::MissingCornerTruncatedBasis)?;
        (basis, QuiverAlgebra::Path(path_algebra.clone()))
    } else {
        let truncated = quotient_by_relations(path_algebra.clone(), &arrow_power)?;
        let basis = truncated
            .canonical_basis()?
            .ok_or(PathalgGbnpError::MissingCornerTruncatedBasis)?;
        (
            basis
                .into_iter()
                .map(|element| element.representative().clone())
                .collect(),
            QuiverAlgebra::Quotient(truncated),
        )
    };

    // Apply AA -> eAe to Basis(AA) and take QPA's left nullspace.
    let image_rows = basis_representatives
        .iter()
        .map(|basis| {
            image_of_path_element(
                corner_algebra,
                &corner_identity,
                basis,
                number_of_vertices,
                &generator_images,
            )
        })
        .collect::<Result<Vec<_>, _>>()?;
    let image_matrix = DenseMatrix::from_flat(
        image_rows.len(),
        corner_algebra.dimension(),
        image_rows.into_iter().flatten().collect(),
        ambient.field().clone(),
    )?;
    let solutions = image_matrix.nullspace_rows();
    let solution_space = solutions.semi_echelon_transformation().vectors;

    // W = J(ker f) + (ker f)J inside V = ker f.
    let truncated_generators = truncated_generators(&truncated_algebra)?;
    let truncated_arrows = &truncated_generators[number_of_vertices..];
    let mut radical_solution_products = Vec::new();
    for arrow in truncated_arrows {
        for row in 0..solution_space.nrows() {
            let solution_representative = linear_combination_of_path_basis(
                &path_algebra,
                &basis_representatives,
                solution_space.row(row),
            )?;
            let solution = truncated_element(&truncated_algebra, solution_representative)?;
            let right = solution.multiply(arrow)?;
            if !right.is_zero() {
                radical_solution_products
                    .push(truncated_coordinates(&basis_representatives, &right)?);
            }
            let left = arrow.multiply(&solution)?;
            if !left.is_zero() {
                radical_solution_products
                    .push(truncated_coordinates(&basis_representatives, &left)?);
            }
        }
    }
    let product_space = span_basis(
        ambient.field(),
        basis_representatives.len(),
        radical_solution_products,
    )?;
    let minimal_relation_rows = quotient_basis_representatives(&solution_space, &product_space)?;
    let mut ideal_generators = Vec::with_capacity(minimal_relation_rows.nrows());
    for row in 0..minimal_relation_rows.nrows() {
        ideal_generators.push(linear_combination_of_path_basis(
            &path_algebra,
            &basis_representatives,
            minimal_relation_rows.row(row),
        )?);
    }

    if ideal_generators.is_empty() {
        Ok(truncated_algebra)
    } else {
        Ok(QuiverAlgebra::Quotient(quotient_by_relations(
            path_algebra,
            &ideal_generators,
        )?))
    }
}

fn quotient_structure_constants<F: Field>(
    quotient: &QuotientPathAlgebra<F>,
    basis: &[qpa_core::QuotientPathAlgebraElement<F>],
) -> Result<StructureConstantsAlgebra<F>, PathalgGbnpError> {
    let dimension = basis.len();
    let mut products = Vec::with_capacity(dimension.saturating_pow(3));
    for left in basis {
        for right in basis {
            let product = left.multiply(right)?;
            products.extend(quotient.canonical_basis_coefficients(&product)?);
        }
    }
    Ok(StructureConstantsAlgebra::new(
        quotient.original_path_algebra().field().clone(),
        dimension,
        products,
    )?)
}

fn ideal_basis<F: Field>(
    algebra: &StructureConstantsAlgebra<F>,
    generators: &[Vec<F::Element>],
) -> Result<DenseMatrix<F>, PathalgGbnpError> {
    let dimension = algebra.dimension();
    let mut products = generators.to_vec();
    for generator in generators {
        for left_index in 0..dimension {
            let left = standard_row(algebra.field(), dimension, left_index);
            let left_product = algebra.multiply_coordinates(&left, generator)?;
            for right_index in 0..dimension {
                let right = standard_row(algebra.field(), dimension, right_index);
                let product = algebra.multiply_coordinates(&left_product, &right)?;
                if !is_zero_row(algebra.field(), &product) {
                    products.push(product);
                }
            }
        }
    }
    Ok(span_basis(algebra.field(), dimension, products)?)
}

fn product_space_basis<F: Field>(
    algebra: &StructureConstantsAlgebra<F>,
    left: &DenseMatrix<F>,
    right: &DenseMatrix<F>,
) -> Result<DenseMatrix<F>, PathalgGbnpError> {
    let mut products = Vec::with_capacity(left.nrows().saturating_mul(right.nrows()));
    for left_row in 0..left.nrows() {
        for right_row in 0..right.nrows() {
            let product = algebra.multiply_coordinates(left.row(left_row), right.row(right_row))?;
            if !is_zero_row(algebra.field(), &product) {
                products.push(product);
            }
        }
    }
    Ok(span_basis(algebra.field(), algebra.dimension(), products)?)
}

fn radical_nilpotency_index<F: Field>(
    algebra: &StructureConstantsAlgebra<F>,
    radical: &DenseMatrix<F>,
) -> Result<usize, PathalgGbnpError> {
    let mut power = radical.clone();
    let mut exponent = 1usize;
    while power.nrows() > 0 {
        power = product_space_basis(algebra, &power, radical)?;
        exponent = exponent
            .checked_add(1)
            .ok_or(PathalgGbnpError::CornerLoewyLengthOverflow)?;
        if exponent > algebra.dimension().saturating_add(1) {
            return Err(PathalgGbnpError::CornerRadicalNotNilpotent);
        }
    }
    Ok(exponent)
}

fn image_of_path_element<F: Field>(
    algebra: &StructureConstantsAlgebra<F>,
    identity: &[F::Element],
    element: &PathAlgebraElement<F>,
    vertex_count: usize,
    images: &[Vec<F::Element>],
) -> Result<Vec<F::Element>, PathalgGbnpError> {
    let mut total = vec![algebra.field().zero(); algebra.dimension()];
    for term in element.terms() {
        let walk = term
            .path()
            .walk()
            .ok_or(PathalgGbnpError::ZeroPathInCornerBasis)?;
        let mut image = if walk.is_empty() {
            let PathEndpoint::Vertex(vertex) = term.path().source() else {
                return Err(PathalgGbnpError::InvalidCornerVertexPath);
            };
            images
                .get(vertex.index().get() - 1)
                .cloned()
                .ok_or(PathalgGbnpError::MissingCornerGeneratorImage)?
        } else {
            let mut product = identity.to_vec();
            for arrow in walk {
                let image = images
                    .get(vertex_count + arrow.get() - 1)
                    .ok_or(PathalgGbnpError::MissingCornerGeneratorImage)?;
                product = algebra.multiply_coordinates(&product, image)?;
            }
            product
        };
        for coefficient in &mut image {
            algebra.field().mul_assign(coefficient, term.coefficient());
        }
        add_row_assign(algebra.field(), &mut total, &image);
    }
    Ok(total)
}

fn truncated_generators<F: Field>(
    algebra: &QuiverAlgebra<F>,
) -> Result<Vec<QuiverAlgebraElement<F>>, PathalgGbnpError> {
    match algebra {
        QuiverAlgebra::Path(algebra) => Ok(algebra
            .generators()
            .into_iter()
            .map(QuiverAlgebraElement::Path)
            .collect()),
        QuiverAlgebra::Quotient(algebra) => Ok(algebra
            .generators()?
            .into_iter()
            .map(QuiverAlgebraElement::Quotient)
            .collect()),
    }
}

fn truncated_element<F: Field>(
    algebra: &QuiverAlgebra<F>,
    representative: PathAlgebraElement<F>,
) -> Result<QuiverAlgebraElement<F>, PathalgGbnpError> {
    match algebra {
        QuiverAlgebra::Path(_) => Ok(QuiverAlgebraElement::Path(representative)),
        QuiverAlgebra::Quotient(quotient) => Ok(QuiverAlgebraElement::Quotient(
            quotient.element(representative)?,
        )),
    }
}

fn truncated_coordinates<F: Field>(
    basis: &[PathAlgebraElement<F>],
    element: &QuiverAlgebraElement<F>,
) -> Result<Vec<F::Element>, PathalgGbnpError> {
    let representative = match element {
        QuiverAlgebraElement::Path(element) => element,
        QuiverAlgebraElement::Quotient(element) => element.representative(),
    };
    let field = representative.algebra().field();
    let mut coordinates = vec![field.zero(); basis.len()];
    for term in representative.terms() {
        let position = basis
            .iter()
            .position(|basis| basis.terms().len() == 1 && basis.terms()[0].path() == term.path())
            .ok_or(PathalgGbnpError::CornerProductOutsideTruncatedBasis)?;
        coordinates[position] = term.coefficient().clone();
    }
    Ok(coordinates)
}

fn quotient_basis_representatives<F: Field>(
    space: &DenseMatrix<F>,
    subspace: &DenseMatrix<F>,
) -> Result<DenseMatrix<F>, PathalgGbnpError> {
    let field = space.field();
    if space.nrows() == 0 {
        return Ok(DenseMatrix::from_flat(
            0,
            space.ncols(),
            Vec::new(),
            field.clone(),
        )?);
    }
    let mut subspace_coordinates = Vec::with_capacity(subspace.nrows() * space.nrows());
    for row in 0..subspace.nrows() {
        subspace_coordinates.extend(
            space
                .solution_row(subspace.row(row))?
                .ok_or(PathalgGbnpError::CornerKernelProductOutsideKernel)?,
        );
    }
    let mut quotient_kernel = DenseMatrix::from_flat(
        subspace.nrows(),
        space.nrows(),
        subspace_coordinates,
        field.clone(),
    )?
    .semi_echelon_transformation()
    .vectors;
    let mut lifts = Vec::new();
    for coordinate in 0..space.nrows() {
        let mut standard = vec![field.zero(); space.nrows()];
        standard[coordinate] = field.one();
        let mut candidate_entries = quotient_kernel.as_flat().to_vec();
        candidate_entries.extend_from_slice(&standard);
        let candidate = DenseMatrix::from_flat(
            quotient_kernel.nrows() + 1,
            space.nrows(),
            candidate_entries,
            field.clone(),
        )?
        .semi_echelon_transformation()
        .vectors;
        if candidate.nrows() > quotient_kernel.nrows() {
            lifts.extend(standard);
            quotient_kernel = candidate;
        }
    }
    Ok(DenseMatrix::from_flat(
        lifts.len() / space.nrows(),
        space.nrows(),
        lifts,
        field.clone(),
    )?
    .multiply(space)?)
}

fn linear_combination_of_path_basis<F: Field>(
    algebra: &PathAlgebra<F>,
    basis: &[PathAlgebraElement<F>],
    coefficients: &[F::Element],
) -> Result<PathAlgebraElement<F>, PathalgGbnpError> {
    Ok(algebra.from_terms(
        basis
            .iter()
            .zip(coefficients)
            .flat_map(|(element, scalar)| {
                element.terms().iter().map(move |term| {
                    (
                        term.path().clone(),
                        algebra.field().mul(scalar, term.coefficient()),
                    )
                })
            }),
    )?)
}

fn span_basis<F: Field>(
    field: &F,
    width: usize,
    rows: Vec<Vec<F::Element>>,
) -> Result<DenseMatrix<F>, qpa_core::MatrixError> {
    DenseMatrix::from_flat(
        rows.len(),
        width,
        rows.into_iter().flatten().collect(),
        field.clone(),
    )
    .map(|matrix| matrix.semi_echelon_transformation().vectors)
}

fn standard_row<F: Field>(field: &F, width: usize, position: usize) -> Vec<F::Element> {
    let mut row = vec![field.zero(); width];
    row[position] = field.one();
    row
}

fn is_zero_row<F: Field>(field: &F, row: &[F::Element]) -> bool {
    row.iter().all(|entry| field.is_zero(entry))
}

fn add_row_assign<F: Field>(field: &F, target: &mut [F::Element], source: &[F::Element]) {
    for (target, source) in target.iter_mut().zip(source) {
        field.add_assign(target, source);
    }
}

